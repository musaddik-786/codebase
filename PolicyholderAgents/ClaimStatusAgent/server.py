class State(TypedDict):
    messages: Annotated[list, add_messages]


def router(state: State):
    last = state["messages"][-1]
    if isinstance(last, AIMessage) and getattr(last, "tool_calls", None):
        return "tools"
    if isinstance(last, AIMessage) and last.content:
        if "Continue" in last.content:
            return "tools"
        if "End" in last.content:
            return "End"
    return "End"


_FALLBACK_PROMPT = """
You are the Claim Status Agent ("Follow My Claim") for an insurance claims
platform. Your job is to keep policyholders informed about where their
claim stands and what is happening next.

─── STEP 0 — Determine whether a tool call is needed ───────────────────────
Only call tools when the policyholder is asking about a SPECIFIC claim.

If the message is a general question (e.g. "How long does a claim take?",
"What does 'Under Review' mean?") — answer from your knowledge WITHOUT
calling any tools, then end with "End".

─── STEP 1 — Extract the claim number ──────────────────────────────────────
Before calling any tool, identify the claim number from the CURRENT message
only. Do NOT use claim numbers from earlier in the conversation.

If no claim number is present, ask:
  "Could you share your claim number so I can look up the latest status?"
Do not call any tool until the policyholder provides it.

─── STEP 2 — Retrieve status and journey ───────────────────────────────────
1. Call get_claim_status_summary — returns current stage, sub-status,
   SLA status, and expected completion date.
   If the result contains an "error" key, tell the policyholder the claim
   was not found and ask them to double-check the number.
2. Call get_claim_journey — returns the full stage history and SLA tracking.

─── STEP 3 — Explain clearly in plain language ─────────────────────────────
- What stage the claim is currently at and what that means.
- The sub-status (e.g. "Under Review", "Awaiting Documents").
- Whether the claim is on track or delayed — if overall_sla_status is not
  "on_track", gently set expectations about possible delays.
- What the policyholder can expect next.

─── STEP 4 — Log policyholder actions (when reported) ──────────────────────
If the policyholder mentions an action they took (e.g. "I uploaded a photo",
"I called my adjuster"), call log_policyholder_action with an appropriate
action_type and action_label, then acknowledge that you have logged it.

You may also call get_policyholder_actions if they ask to see their action
history.

─── RULES ───────────────────────────────────────────────────────────────────
- NEVER assume or guess a claim number — always take it from the current message.
- NEVER expose internal IDs or raw database fields.
- Be warm, clear, and reassuring.
- When you have completed the full response, end with "End".
"""


def load_prompt() -> str:
    if not PHOENIX_ENDPOINT:
        raise RuntimeError("Phoenix not configured")
    from phoenix.client import Client
    client = Client(base_url=PHOENIX_ENDPOINT, api_key=PHOENIX_API_KEY)
    prompt = client.prompts.get(name="claim_status_agent", label="production")
    prompt_set = prompt._template["messages"]
    system_msg = next(
        (item["content"][0]["text"] for item in prompt_set if item.get("role") == "system"),
        None,
    )
    if not system_msg:
        raise ValueError("System prompt is empty or missing in Phoenix")
    return system_msg


def create_graph(model, tools, prompt):
    graph_builder = StateGraph(State)
    llm_with_tools = model.bind_tools(tools)

    async def agent_node(state: State):
        messages = state["messages"]
        all_messages = [SystemMessage(content=prompt)] + messages
        message = await llm_with_tools.ainvoke(all_messages)
        return {"messages": [message]}

    graph_builder.add_node("agent", agent_node)
    graph_builder.add_node("tools", ToolNode(tools=tools))
    graph_builder.add_edge(START, "agent")
    graph_builder.add_conditional_edges("agent", router, {"tools": "tools", "End": END})
    graph_builder.add_edge("tools", "agent")
    return graph_builder.compile()


async def get_tools():
    client = MultiServerMCPClient(config_mcp_server)
    tools = await client.get_tools()
    logger.info("Tools loaded from MCP: %s", [t.name for t in tools])
    return tools


async def stream_graph(graph, initial_state, config):
    async for event in graph.astream_events(initial_state, config=config, version="v2"):
        kind = event.get("event", "")

        if kind == "on_chat_model_stream":
            chunk = event["data"].get("chunk")
            if chunk and hasattr(chunk, "content") and chunk.content:
                yield f"data: {chunk.content}\n\n"

        elif kind == "on_tool_start":
            tool_name = event.get("name", "unknown_tool")
            yield f"data: [Tool: {tool_name}] Starting...\n\n"

        elif kind == "on_tool_end":
            tool_name = event.get("name", "unknown_tool")
            yield f"data: [Tool: {tool_name}] Done\n\n"


@app.post("/chat")
async def chat_stream(request: Request):
    load_dotenv(find_dotenv())

    tools = await get_tools()

    model = AzureChatOpenAI(
        api_key=os.getenv("AZURE_OPENAI_API_KEY"),
        api_version=os.getenv("AZURE_OPENAI_API_VERSION"),
        azure_deployment=os.getenv("AZURE_OPENAI_CHAT_DEPLOYMENT"),
        azure_endpoint=os.getenv("AZURE_OPENAI_ENDPOINT"),
    )

    try:
        system_prompt = load_prompt()
    except Exception as e:
        logger.warning("Phoenix prompt load failed (%s) — using fallback prompt", e)
        system_prompt = _FALLBACK_PROMPT

    body = await request.json()
    user_message = body.get("message", "What's the status of my claim?")

    graph = create_graph(model=model, tools=tools, prompt=system_prompt)

    async def generate():
        start = time.time()
        last_event_at = start
        last_tool = None
        try:
            async for event in stream_graph(
                graph=graph,
                initial_state={"messages": [user_message]},
                config={"recursion_limit": 250},
            ):
                last_event_at = time.time()
                if isinstance(event, str) and event.startswith("data: [Tool:"):
                    try:
                        last_tool = event.split("[Tool:", 1)[1].split("]", 1)[0]
                    except Exception:
                        pass
                yield event
        except BaseException as e:
            elapsed = time.time() - start
            since_last = time.time() - last_event_at
            err = {
                "exception_class": type(e).__name__,
                "message": str(e),
                "elapsed_total_seconds": round(elapsed, 2),
                "seconds_since_last_event": round(since_last, 2),
                "last_tool_invoked": last_tool,
                "traceback": traceback.format_exc(),
                "timestamp_utc": datetime.utcnow().isoformat(),
            }
            logger.error("AGENT_ERROR %s", json.dumps(err, default=str))
            try:
                yield f"data: [AGENT_ERROR] {json.dumps(err, default=str)}\n\n"
            except Exception:
                pass
            import asyncio
            if isinstance(e, asyncio.CancelledError):
                raise

    return StreamingResponse(generate(), media_type="text/event-stream")


